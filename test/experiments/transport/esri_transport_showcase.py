"""Geometry inspection: external operation outputs closed by our own display helper."""

import hashlib
import json
from pathlib import Path
import subprocess

import numpy as np
import shapely

from outshine_ref.contracts import Mesh
from outshine_ref.transport import close_surface
from esri_transport_comparison import own_triangles
from surface_solid_showcase import write_case


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUTPUT = ROOT / "build/experiments/transport/esri-reference/inspection"


def top_surface(domain):
    vertices, faces = [], []
    offset = 0
    for polygon in shapely.get_parts(domain):
        xy, indices = own_triangles(polygon)
        vertices.append(np.c_[xy, np.zeros(len(xy))])
        faces.append(indices + offset)
        offset += len(xy)
    return Mesh(np.vstack(vertices), np.vstack(faces))


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    comparison = json.loads((OUTPUT.parent / "comparison.json").read_text())
    offset = next(r for r in comparison["offsets"] if r["id"] == "dumbbell")
    pairs = [("offset-fragments", [("python", top_surface(shapely.from_wkt(offset["python_wkt"]))),
                                   ("sdk-helper", top_surface(shapely.from_wkt(offset["sdk_wkt"])))] )]
    for case in ("courtyard", "Vienna-junction-0"):
        with np.load(OUTPUT.parent / (case + "-triangles.npz")) as data:
            pairs.append((case, [("python", Mesh(data["own_vertices"], data["own_faces"])),
                                 ("sdk-backend", Mesh(data["sdk_vertices"], data["sdk_faces"]))]))
    configurations = []
    for name, models in pairs:
        start = len(configurations)
        for method, mesh in models:
            solid = close_surface(mesh, .35)
            record = dict(operation=name, method=method, binary_sha256=comparison["offsets"][0]["binary_sha256"],
                          scope="Primitive geometry only, flat assumed height; 0.35 m display body generated by our close_surface, not an SDK Processor extrusion. SDK backend degenerate primitives/conformance explicitly audited in comparison.json. Same camera, no height exaggeration.")
            write_case("SDK-reference-" + name + "-" + method, solid, np.zeros(len(solid.triangles), dtype=int), record,
                       configurations, output_dir=OUTPUT)
            for key in ("eye", "target", "span_m", "profile"):
                configurations[-1][key] = configurations[start][key]
    scene = OUTPUT / "scenes.json"
    scene.write_text(json.dumps(configurations, indent=2) + "\n")
    subprocess.run(["blender", "--background", "--factory-startup", "--python-exit-code", "1", "--python",
                    str(HERE / "render_transport_solid.py"), "--", str(scene)], cwd=ROOT, check=True)
    records = {}
    for row in configurations:
        stem = OUTPUT / (row["id"] + "-solid")
        records[stem.name] = dict(image_sha256=hashlib.sha256(stem.with_suffix(".png").read_bytes()).hexdigest(),
                                  report_sha256=hashlib.sha256(stem.with_suffix(".json").read_bytes()).hexdigest())
    (OUTPUT / "origin.json").write_text(json.dumps(dict(commit=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip(),
                                                       working_tree_dirty=bool(subprocess.check_output(["git", "status", "--porcelain", "--", "test/experiments/transport"], cwd=ROOT, text=True)),
                                                       records=records), indent=2) + "\n")


if __name__ == "__main__":
    main()
