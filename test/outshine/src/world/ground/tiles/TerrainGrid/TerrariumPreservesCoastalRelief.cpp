#include <cstdint>
#include "tiles/TerrainGrid.h"
#include "Check.h"

int main() {
  using namespace outshine::Test;
  constexpr uint8_t png[] = {
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
      0x52, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x04, 0x08, 0x02, 0x00, 0x00, 0x00, 0x08,
      0xd6, 0x28, 0xbb, 0x00, 0x00, 0x00, 0x21, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0x68,
      0xb0, 0x65, 0x20, 0x80, 0x16, 0x32, 0x34, 0xb2, 0x32, 0x34, 0x66, 0x32, 0x34, 0x9e, 0x65,
      0x68, 0x32, 0x64, 0x20, 0xa4, 0x7a, 0x00, 0x34, 0x00, 0x00, 0x57, 0xeb, 0x32, 0xc5, 0x0a,
      0xb4, 0xfd, 0x3b, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};
  const auto grid = outshine::Ground::TerrainGrid::FromTerrariumPng(png, sizeof png);
  const auto *field = grid.TryField();
  CHECK(field != nullptr, "Terrarium lake and hillside decode");
  if (!field) { return Report(); }
  for (uint32_t row = 0; row < 4; ++row) {
    for (uint32_t col = 0; col < 16; ++col) {
      const float height = col < 11 ? 61.0f : 61.0f + 100.0f * static_cast<float>(col - 10);
      CHECK_NEAR(field->AtM(row, col),
                 height,
                 0.0f,
                 "m",
                 "a majority lake must not erase the minority hillside");
    }
  }
  return Report();
}
