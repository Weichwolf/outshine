#include <algorithm>
#include <array>
#include <cstdint>

#include "Check.h"
#include "Png.h"

int main() {
  using namespace outshine::Test;
  // Two RGB rows: 10..60 then 15..65. The second uses Paeth with residual 5 per byte.
  // At its second pixel, above=40 and upper-left=10: the predictor must choose 40.
  constexpr uint8_t png[] = {
      0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44,
      0x52, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x02, 0x08, 0x02, 0x00, 0x00, 0x00, 0xfd,
      0xd4, 0x9a, 0x73, 0x00, 0x00, 0x00, 0x12, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9c, 0x63, 0xe0,
      0x12, 0x91, 0xd3, 0x30, 0xb2, 0x61, 0x61, 0x05, 0x03, 0x00, 0x08, 0x81, 0x00, 0xf5, 0x9b,
      0x68, 0x36, 0x1d, 0x00, 0x00, 0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, 0x60, 0x82};
  constexpr std::array<uint8_t, 12> expected = {10, 20, 30, 40, 50, 60, 15, 25, 35, 45, 55, 65};
  const auto read = outshine::Io::ReadPng(png, sizeof png);
  CHECK(read.Read && read.Wide == 2 && read.High == 2 && read.Channels == 3,
        "the independent PNG fixture is a two-by-two RGB image");
  CHECK(std::ranges::equal(read.Bytes, expected),
        "Paeth preserves every encoded byte, including the upper-left neighbour's contribution");
  Covers("board:2166 -- elevation RGB bytes survive PNG prediction without fabricated heights");
  return Report();
}
