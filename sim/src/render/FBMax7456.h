/* Blit one glyph: 6 verts (2 tris), x,y,u,v,r,g,b, quad at (x,y) size qs px, UV over glyph `gi`'s 8x8
 * tile (inset 0.05 texel so NEAREST never lands on a cell boundary and picks a neighbour). */
inline void Max7456AppendGlyph(std::vector<float> &out, float x, float y, float qs, int gi, float r,
                                float g, float b) {
  float u0 = ((float)gi * kMax7456Tile + 0.05f) / kMax7456AtlasW,
        u1 = ((float)gi * kMax7456Tile + kMax7456Tile - 0.05f) / kMax7456AtlasW;
  float v0 = 0.05f / kMax7456Tile, v1 = (kMax7456Tile - 0.05f) / kMax7456Tile, x1 = x + qs, y1 = y + qs;
  auto vert = [&](float px, float py, float pu, float pv) {
    out.insert(out.end(), {px, py, pu, pv, r, g, b});
  };
  vert(x, y, u0, v0);
  vert(x1, y, u1, v0);
  vert(x1, y1, u1, v1);
  vert(x, y, u0, v0);
  vert(x1, y1, u1, v1);
  vert(x, y1, u0, v1);
}

/* Appends a whole string as glyph quads (drop-in for the old mx_text contract: x,y top-left, scale s,
 * colour, string). Unknown/lowercase-folded chars fall to the blank tile (index 0). */
inline void Max7456AppendText(std::vector<float> &out, float x, float y, float s, float r, float g,
                               float b, const char *text) {
  float adv = kMax7456Advance * s, qs = kMax7456QuadSize * s;
  for (; *text; text++) {
    char u = *text;
    if (u >= 'a' && u <= 'z') u -= 32;
    const char *p = strchr(kMax7456Charset, u);
    int gi = p ? (int)(p - kMax7456Charset) : 0;
    if (gi > 0) Max7456AppendGlyph(out, x, y, qs, gi, r, g, b);
    x += adv;
  }
}

