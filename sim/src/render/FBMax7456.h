/* FlightBox — FBMax7456: emulation of the character-generator OSD chip real FPV ground stations use.
 * A font ROM of 8x8 pixel tiles is baked once into an atlas texture (FBHudStage::Init); text is then
 * composed as textured-quad blits of those tiles, exactly as the chip paints characters from its tile
 * ROM. Render-backend resource: the atlas layout (glyph count/tile size/advance) is shared by every
 * consumer that blits MAX7456 glyphs (FBHudGeometry::Text, FBHudStage's loading screen).
 *
 * The tile ROM is generated from readable glyph art (scratchpad/genfont.py) -- the art is the spec, the
 * bytes below are its output, so there is no transcription drift. NEAREST sampling + alpha-test discard
 * (FBHudStage's WGSL) keeps the glyphs crisp and blocky (authentic chip look).
 *
 * Pure data + a free function appending glyph quads to a caller-owned vector -- no globals, no GL. */
